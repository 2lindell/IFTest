CREATE OR REPLACE FUNCTION public.get_kind_parents(p_kind_id integer)
 RETURNS TABLE(parent_kind_id integer)
 LANGUAGE sql
AS $function$
  with recursive ancestors as (
    -- start from the direct parent(s)
    select
      ak.kind_parent_id as current_kind_id
    from "All Kinds" ak
    where ak.kind_id = p_kind_id
      and ak.kind_parent_id is not null

    union all

    -- climb upwards: parent of the current node
    select
      ak2.kind_parent_id as current_kind_id
    from "All Kinds" ak2
    join ancestors a
      on ak2.kind_id = a.current_kind_id
    where ak2.kind_parent_id is not null
  )
  select distinct current_kind_id as parent_kind_id
  from ancestors
  order by parent_kind_id;
$function$
;

CREATE OR REPLACE FUNCTION public.kind_of_entity(p_kind_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE
AS $function$
  select exists (
    select 1
    from get_kind_parents(p_kind_id::integer) gp
    join "All Kinds" pk on pk.kind_id = gp.parent_kind_id::bigint
    where pk.kind_name = 'Entity'
  );
$function$
;

CREATE OR REPLACE FUNCTION public.make_list(elements text[], conjunction text DEFAULT 'and'::text)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
DECLARE
    list_length INT := array_length(elements, 1);
BEGIN
    -- Handle empty or null arrays
    IF elements IS NULL OR list_length IS NULL OR list_length = 0 THEN
        RETURN '';
    END IF;

    -- Clean conjunction input (remove spaces, lowercase)
    conjunction := lower(trim(conjunction));

    -- Validate conjunction type
    IF conjunction NOT IN ('and', 'or') THEN
        RAISE EXCEPTION 'Conjunction must be either ''and'' or ''or''';
    END IF;

    -- Format based on element count
    CASE list_length
        WHEN 1 THEN 
            RETURN elements[1];
        WHEN 2 THEN 
            RETURN elements[1] || ' ' || conjunction || ' ' || elements[2];
        ELSE 
            -- Uses the Oxford Comma format
            RETURN array_to_string(elements[1 : list_length - 1], ', ') || ', ' || conjunction || ' ' || elements[list_length];
    END CASE;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.trg_kind_properties_validate_implications()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  imp text;
  new_base_prop_adjective text;
  all_ok boolean;
begin
  if NEW.kindproperty_implication is null then
    return NEW;
  end if;

  select p.property_adjective
  into new_base_prop_adjective
  from public."Properties" p
  where p.property_id = NEW.kindproperty_property_id;

  if new_base_prop_adjective is null then
    raise exception
      'Invalid insert/update: Properties.property_adjective must be non-null for kindproperty_property_id=%',
      NEW.kindproperty_property_id;
  end if;

  if array_length(NEW.kindproperty_implication, 1) is null then
    return NEW;
  end if;

  all_ok := true;

  foreach imp in array NEW.kindproperty_implication
  loop
    if imp is null then
      all_ok := false;
      exit;
    end if;

    if not exists (
      select 1
      from public."Kind-Properties" kp2
      join public."Properties" p2
        on p2.property_id = kp2.kindproperty_property_id
      where kp2.kindproperty_kind_id = NEW.kindproperty_kind_id
        and kp2.kindproperty_property_id <> NEW.kindproperty_property_id
        and (
          imp = p2.property_adjective
          or imp = p2.property_opposite_adjective
          or (
            p2.property_opposite_adjective is null
            and imp = ('not ' || p2.property_adjective)
          )
        )
    ) then
      all_ok := false;
      exit;
    end if;
  end loop;

  if all_ok then
    return NEW;
  end if;

  raise exception
    'Invalid insert/update: one or more kindproperty_implication values must match property_adjective or property_opposite_adjective (or "not "||property_adjective when opposite is null) from a different Kind-Properties row with same kindproperty_kind_id=%',
    NEW.kindproperty_kind_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.validate_jsonb_key_matches_kind()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$DECLARE
  v_kind_id_col     text := TG_ARGV[0]; -- Name of the column holding the kind_id (or property_id, in this special case)
  v_jsonb_col       text := TG_ARGV[1]; -- Name of the column holding the jsonb data
  v_kind_id_val     int;
  v_jsonb_val       jsonb;
  v_kind_name_key   text;
  v_key_count       int;
BEGIN
  -- 1. Use RECORD features to dynamically extract values from the row
  EXECUTE format('SELECT ($1).%I, ($1).%I', v_kind_id_col, v_jsonb_col)
  USING NEW
  INTO v_kind_id_val, v_jsonb_val;

  -- EARLY RETURN: Safely allow structural null values or unassigned values to pass through
  if v_jsonb_val is null or v_jsonb_val = 'null'::jsonb or v_kind_id_val is null then
    return NEW;
  end if;

  -- NEW: If the column name contains "property_id", resolve it to property_kind_id first
  IF v_kind_id_col ILIKE '%property_id%' THEN
    SELECT p."property_kind_id"
    INTO v_kind_id_val
    FROM "Properties" p
    WHERE p."property_id" = v_kind_id_val;

    -- Fail if the linked property data does not exist
    IF v_kind_id_val IS NULL THEN
      return new;
    END IF;
  END IF;

  -- 2. Fetch and lowercase the kind_name from "All Kinds" using the (resolved) kind id
  SELECT lower(k.kind_name) INTO v_kind_name_key 
  FROM "All Kinds" k 
  WHERE k.kind_id = v_kind_id_val;

  -- 3. Fail if the linked kind data does not exist
  IF v_kind_name_key IS NULL THEN
    RAISE EXCEPTION 'Foreign key % (% = %) not found in "All Kinds"', 
                    v_kind_id_col, v_kind_id_col, v_kind_id_val;
  END IF;

  -- 4. Check structural rules: must be a valid JSON object
  IF jsonb_typeof(v_jsonb_val) != 'object' THEN
    RAISE EXCEPTION 'Column % must be a valid JSON object', v_jsonb_col;
  END IF;

  -- 5. Count the number of unique keys at the root of the JSON object
  SELECT count(*) INTO v_key_count 
  FROM jsonb_object_keys(v_jsonb_val);

 -- 6. Enforce that the JSON object's single key matches:
  --    - the configured kind name, OR
  --    - any child kind of that kind
  IF v_key_count != 1 THEN
    RAISE EXCEPTION 'JSON object in % must contain exactly one key named "%"', 
                    v_jsonb_col, v_kind_name_key;
  END IF;

  -- Get the single key (root JSON key)
  SELECT lower(j.key)
  INTO v_kind_name_key
  FROM jsonb_object_keys(v_jsonb_val) AS j(key)
  LIMIT 1;

  -- Allow exact match
  IF v_kind_name_key = (
      SELECT lower(k.kind_name)
      FROM "All Kinds" k
      WHERE k.kind_id = v_kind_id_val
  ) THEN
    RETURN NEW;
  END IF;

  -- Otherwise, treat the JSON key as a kind_name, resolve it to a kind_id
  DECLARE
    v_json_kind_id int;
  BEGIN
    SELECT k.kind_id
    INTO v_json_kind_id
    FROM "All Kinds" k
    WHERE lower(k.kind_name) = v_kind_name_key;

    IF v_json_kind_id IS NULL THEN
      RAISE EXCEPTION 'JSON key "%" in % does not match any kind_name in "All Kinds"', 
        v_kind_name_key, v_jsonb_col;
    END IF;

    -- Check whether the configured kind is a parent (ancestor) of the JSON key's kind
    IF NOT EXISTS (
      SELECT 1
      FROM get_kind_parents(v_json_kind_id::integer) gp
      WHERE gp.parent_kind_id::int = v_kind_id_val
    ) THEN
      RAISE EXCEPTION
        'JSON object in % must contain key "%" or a child kind of that kind. Got "%".',
        v_jsonb_col,
        (SELECT lower(k.kind_name) FROM "All Kinds" k WHERE k.kind_id = v_kind_id_val),
        v_kind_name_key;
    END IF;
  END;

  RETURN NEW;
END;$function$
;

CREATE OR REPLACE FUNCTION public.validate_jsonb_value_matches_type()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$declare 
  v_fk_col_name   text := TG_ARGV[0]; 
  v_jsonb_col     text := TG_ARGV[1]; 

  v_fk_val        int;       
  v_outer_json    jsonb;
  v_target_type   regtype;
  v_json_kind_id  bigint;
  
  -- Unwrapped single-object components
  v_inner_key     text;
  v_inner_jsonb   jsonb;
  v_inner_type    text;
  v_txt_val       text;

  -- NEW: for the property_kind_id IS NULL fallback
  v_property_adjective         text;
  v_property_opposite_adjective text;
begin 
  -- 1. Extract the raw foreign key value and the outer JSON wrapper from the row
  execute format('select ($1).%I, ($1).%I', v_fk_col_name, v_jsonb_col) 
    using NEW 
    into v_fk_val, v_outer_json;

  -- If JSON itself is empty/unassigned, let it through
  if v_outer_json is null or v_outer_json = 'null'::jsonb then
    return NEW;
  end if;

  -- 1.5 NEW: If the argument column name contains "property_id", resolve it to property_kind_id first.
  --       If property_kind_id is NULL, run the alternative adjective validation (instead of returning NEW).
  if v_fk_col_name ILIKE '%property_id%' then
    declare
      v_property_kind_id int;
    begin
      select p."property_kind_id"
      into v_property_kind_id
      from "Properties" p
      where p."property_id" = v_fk_val;

    if v_property_kind_id is null then
        -- Fetch adjectives for fallback matching
        select p."property_adjective", p."property_opposite_adjective"
        into v_property_adjective, v_property_opposite_adjective
        from "Properties" p
        where p."property_id" = v_fk_val;

        -- JSON must be a JSON string scalar (text in quotes)
        if jsonb_typeof(v_outer_json) <> 'string' then
          raise exception 'Data rejection on table "%": Column "%" expects a quoted text JSON string (e.g. "value"), but received %.',
            TG_TABLE_NAME, v_jsonb_col, jsonb_typeof(v_outer_json);
        end if;

        v_txt_val := v_outer_json #>> '{}'; -- unquoted text

        -- property_adjective must exist (per your rule)
        if v_property_adjective is null then
          raise exception 'Data rejection on table "%": Properties.property_adjective is NULL for property_id=%.',
            TG_TABLE_NAME, v_fk_val;
        end if;

        -- Acceptable values:
        -- 1) property_adjective always
        -- 2) property_opposite_adjective if not null
        -- 3) otherwise "not " || property_adjective
        if v_txt_val = v_property_adjective then
          return NEW;
        end if;

        if v_property_opposite_adjective is not null and v_txt_val = v_property_opposite_adjective then
          return NEW;
        end if;

        if v_property_opposite_adjective is null and v_txt_val = ('not ' || v_property_adjective) then
          return NEW;
        end if;

        raise exception
          'Data rejection on table "%": Column "%" value "%" must match "%"', 
          TG_TABLE_NAME, v_jsonb_col, v_txt_val, v_property_adjective;
      end if;

      -- property_kind_id exists => proceed normally using v_fk_val as the kind_id lookup key
      -- (so we set v_fk_val to property_kind_id for the remainder of the function)
      v_fk_val := v_property_kind_id;
    end;
  end if;

  -- 2. Fetch the expected database column type from the kinds lookup table
  select kind_regtype::regtype into v_target_type 
  from "All Kinds"
  where kind_id = v_fk_val;

  if v_target_type is null then 
    return NEW; 
  end if;

  -- 3. UNWRAP THE SINGLE OBJECT: Extract the single key and its inner jsonb value directly
  if jsonb_typeof(v_outer_json) != 'object' then
    raise exception 'Data rejection on table "%": Column "%" expects a JSON object with exactly one key for non-null kind validation.',
      TG_TABLE_NAME, v_jsonb_col;
  end if;

  select key, value into v_inner_key, v_inner_jsonb 
  from jsonb_each(v_outer_json) 
  limit 1;

  -- 4. Gather accurate types for the inner payload content
  v_inner_type := jsonb_typeof(v_inner_jsonb);
  v_txt_val    := v_inner_jsonb #>> '{}';

-- If the configured kind is "under Entity", ensure v_txt_val exists in Entities
-- and that it belongs to the kind that was actually specified by the JSON key.
if public.kind_of_entity(v_fk_val::integer) then
  -- Convert the JSON object's single key (kind_name) -> kind_id
  select k.kind_id::bigint
  into v_json_kind_id
  from "All Kinds" k
  where lower(k.kind_name) = v_inner_key;

  if v_json_kind_id is null then
    raise exception
      'Data rejection on table "%": Key "%" is not a recognized kind_name in "All Kinds".',
      TG_TABLE_NAME, v_inner_key;
  end if;

  -- Enforce string scalar for entity_name
  if v_inner_type is distinct from 'string' then
    raise exception
      'Data rejection on table "%": Key "%" expects an entity-name string (JSON string) for Entity-backed kinds, but received %.',
      TG_TABLE_NAME, v_inner_key, v_inner_type;
  end if;

  -- Validate entity belongs to the *kind from the JSON key*
  if not exists (
    select 1
    from "Entities" e
    where e.entity_name = v_txt_val
      and e.entity_of_kind_id = v_json_kind_id
  ) then
    raise exception
      'Data rejection on table "%": Key "%" value "%" is not a valid Entities.entity_name for entity_of_kind_id=% (kind taken from JSON key).',
      TG_TABLE_NAME, v_inner_key, v_txt_val, v_json_kind_id;
  end if;
end if;

  -- 5. THE STRICT RULE: Validate text-targeted types
  if v_target_type in ('text'::regtype, 'character varying'::regtype, 'character'::regtype) then
    if v_inner_type in ('number', 'boolean') then
      raise exception 'Data rejection on table "%": The key "%" expects a text value, so its value must be wrapped in double quotes. Received an unquoted % instead.',
        TG_TABLE_NAME, v_inner_key, v_inner_type;
    end if;
  end if;

  -- 6. Perform the dynamic validation cast check against the database target type
  begin
    execute format('select %L::%s', v_txt_val, v_target_type);
  exception 
    when others then
      raise exception 'Data rejection on table "%": Key "%" value (%) cannot be safely cast to the configured database type "%".', 
        TG_TABLE_NAME, v_inner_key, v_outer_json, v_target_type;
  end;

  return NEW;
end;$function$
;

