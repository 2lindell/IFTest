        CASE
            WHEN "Actions".action_out_of_world THEN 'out of world'::text
            ELSE ('applying to '::text ||
            CASE
                WHEN ("Actions".action_indirect_kind IS NOT NULL) THEN
                CASE
                    WHEN ("Actions".action_direct_kind = "Actions".action_indirect_kind) THEN ('two '::text || public.pluralize_noun(lower(k.kind_name)))
                    ELSE ((('one '::text || lower(k.kind_name)) || ' and one '::text) || lower(k2.kind_name))
                END
                WHEN ("Actions".action_direct_kind IS NOT NULL) THEN ('one '::text || lower(k.kind_name))
                ELSE 'nothing'::text
            END)
        END) || '.'::text) AS action_assertion,
    "Actions".action_id,
    "Actions".action_name,
    k.kind_name AS action_direct_kind_name,
    k2.kind_name AS action_indirect_kind_name,
    "Actions".action_out_of_world
   FROM ((public."Actions"
     LEFT JOIN public."All Kinds" k ON ((k.kind_id = "Actions".action_direct_kind)))
     LEFT JOIN public."All Kinds" k2 ON ((k2.kind_id = "Actions".action_indirect_kind)));


